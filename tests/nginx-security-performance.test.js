import assert from 'node:assert/strict';
import test from 'node:test';

import {composeNginxCapabilities, composeNginxSites} from '../dist/nginx-composition/index.js';
import {block, directive, nginxArgument as arg, serializeNginxDocument} from '../dist/nginx-syntax/index.js';

const target = {version: '1.30.6', modules: ['http_gzip', 'http_headers', 'http_map', 'http_proxy', 'http_rewrite', 'http_ssl']};
const proxy = {id: 'reverse-proxy', input: {domain: 'app.example.com', targetHost: '127.0.0.1', targetPort: 3000}};
const staticSite = {id: 'static-site', input: {domain: 'static.example.com', documentRoot: '/srv/www/app', indexFile: 'index.html', spaFallback: true}};
const tls = {id: 'tls', input: {certificatePath: '/etc/nginx/certs/app.pem', privateKeyPath: '/etc/nginx/private/app.key', redirectHttp: true}};
const security = (overrides = {}) => ({id: 'security-headers', input: {preset: 'balanced', hsts: 'off', ...overrides}});
const timeouts = (overrides = {}) => ({id: 'request-timeouts', input: {
  clientMaxBodySizeMb: 10, clientBodyTimeoutSeconds: 30, clientHeaderTimeoutSeconds: 15, sendTimeoutSeconds: 60,
  proxy: {connectSeconds: 10, sendSeconds: 60, readSeconds: 120}, ...overrides,
}});
const compression = (overrides = {}) => ({id: 'compression', input: {types: ['text/css', 'application/json'], minLengthBytes: 1024, level: 5, vary: true, ...overrides}});
const buffering = (overrides = {}) => ({id: 'proxy-buffering', input: {profile: 'bounded', bufferSizeKb: 8, bufferCount: 8, busyBuffersSizeKb: 16, maxTempFileSizeMb: 64, ...overrides}});
const compose = capabilities => composeNginxCapabilities({profile: 'full-config', target, capabilities});

test('new capabilities are opt-in and leave existing generated bytes unchanged', () => {
  const first = compose([proxy]);
  const second = compose([proxy]);
  assert.equal(first.ok, true);
  assert.deepEqual(second.artifacts, first.artifacts);
  assert.doesNotMatch(first.artifacts[0].content, /(?:add_header|client_max_body_size|gzip|proxy_buffering)/u);
});

test('security presets emit fixed inherited headers and HTTPS-only HSTS', () => {
  const plain = compose([proxy, security({preset: 'strict'})]);
  assert.equal(plain.ok, true, JSON.stringify(plain.diagnostics));
  assert.match(plain.artifacts[0].content, /add_header Content-Security-Policy "default-src 'none';/u);
  assert.match(plain.artifacts[0].content, /add_header X-Content-Type-Options "nosniff" always;/u);
  assert.match(plain.artifacts[0].content, /add_header X-Frame-Options "DENY" always;/u);
  assert.match(plain.artifacts[0].content, /add_header Referrer-Policy "no-referrer" always;/u);
  assert.match(plain.artifacts[0].content, /add_header Permissions-Policy /u);
  assert.equal((plain.artifacts[0].content.match(/add_header/g) ?? []).length, 5);
  assert.ok(plain.prerequisites.some(item => item.code === 'composition.security-headers.compatibility.strict'));

  const secure = compose([proxy, tls, security({hsts: 'two-years-preload'})]);
  assert.equal(secure.ok, true, JSON.stringify(secure.diagnostics));
  assert.equal((secure.artifacts[0].content.match(/Strict-Transport-Security/g) ?? []).length, 1);
  const redirectEnd = secure.artifacts[0].content.indexOf('return 301');
  const hsts = secure.artifacts[0].content.indexOf('Strict-Transport-Security');
  assert.ok(hsts > redirectEnd);
  assert.ok(secure.prerequisites.some(item => item.code === 'composition.security-headers.hsts-preload'));
});

test('HSTS dependency and arbitrary header injection fail without artifacts', () => {
  const missingTls = compose([proxy, security({hsts: 'one-year'})]);
  assert.equal(missingTls.ok, false);
  assert.deepEqual(missingTls.artifacts, []);
  assert.ok(missingTls.diagnostics.some(item => item.code === 'composition.security-headers.hsts-requires-tls'));
  for (const input of [
    {preset: "strict; add_header X-Pwned yes", hsts: 'off'},
    {preset: 'balanced', hsts: 'max-age=1; includeSubDomains'},
    {preset: 'balanced', hsts: ['off']},
  ]) {
    const result = compose([proxy, {id: 'security-headers', input}]);
    assert.equal(result.ok, false);
    assert.deepEqual(result.artifacts, []);
  }
});

test('request and proxy timeouts use bounded typed values on proxy and static sites', () => {
  const proxied = compose([proxy, timeouts()]);
  assert.equal(proxied.ok, true, JSON.stringify(proxied.diagnostics));
  for (const expected of ['client_max_body_size 10m;', 'client_body_timeout 30s;', 'client_header_timeout 15s;', 'send_timeout 60s;', 'proxy_connect_timeout 10s;', 'proxy_send_timeout 60s;', 'proxy_read_timeout 120s;']) assert.match(proxied.artifacts[0].content, new RegExp(expected));

  const staticResult = compose([staticSite, timeouts({proxy: undefined})]);
  assert.equal(staticResult.ok, true, JSON.stringify(staticResult.diagnostics));
  assert.doesNotMatch(staticResult.artifacts[0].content, /proxy_(?:connect|send|read)_timeout/u);
  const invalidOwner = compose([staticSite, timeouts()]);
  assert.equal(invalidOwner.ok, false);
  assert.ok(invalidOwner.diagnostics.some(item => item.code === 'composition.capability.proxy-owner'));
});

test('timeout bounds and coercion or injection values are rejected', () => {
  const mutations = [
    {clientMaxBodySizeMb: 0}, {clientBodyTimeoutSeconds: 301}, {clientHeaderTimeoutSeconds: '30'}, {sendTimeoutSeconds: 3601},
    {proxy: {connectSeconds: 76, sendSeconds: 60, readSeconds: 60}},
    {proxy: {connectSeconds: 10, sendSeconds: '60s; return 200', readSeconds: 60}},
  ];
  for (const mutation of mutations) {
    const result = compose([proxy, timeouts(mutation)]);
    assert.equal(result.ok, false, JSON.stringify(mutation));
    assert.deepEqual(result.artifacts, []);
  }
});

test('compression serializes a canonical MIME allowlist with explicit side-channel warnings', () => {
  const result = compose([proxy, compression({types: ['text/css', 'application/json', 'image/svg+xml']})]);
  const reordered = compose([compression({types: ['image/svg+xml', 'application/json', 'text/css']}), proxy]);
  assert.equal(result.ok, true, JSON.stringify(result.diagnostics));
  assert.deepEqual(reordered.artifacts, result.artifacts);
  assert.match(result.artifacts[0].content, /gzip on;/u);
  assert.match(result.artifacts[0].content, /gzip_types application\/json image\/svg\+xml text\/css;/u);
  assert.match(result.artifacts[0].content, /gzip_min_length 1024;/u);
  assert.match(result.artifacts[0].content, /gzip_comp_level 5;/u);
  assert.match(result.artifacts[0].content, /gzip_vary on;/u);
  assert.ok(result.prerequisites.some(item => item.code === 'composition.compression.sensitive-data'));
});

test('compression rejects arbitrary MIME tokens, duplicates, unsafe bounds and coercion', () => {
  for (const input of [
    {types: ['text/css; return 200'], minLengthBytes: 1024, level: 5, vary: true},
    {types: ['application/json', 'application/json'], minLengthBytes: 1024, level: 5, vary: true},
    {types: ['application/json'], minLengthBytes: 255, level: 5, vary: true},
    {types: ['application/json'], minLengthBytes: 1024, level: 10, vary: true},
    {types: ['application/json'], minLengthBytes: 1024, level: 5, vary: 'true'},
  ]) {
    const result = compose([proxy, {id: 'compression', input}]);
    assert.equal(result.ok, false);
    assert.deepEqual(result.artifacts, []);
  }
});

test('proxy buffering supports bounded and streaming profiles with resource invariants', () => {
  const bounded = compose([proxy, buffering()]);
  assert.equal(bounded.ok, true, JSON.stringify(bounded.diagnostics));
  for (const expected of ['proxy_buffering on;', 'proxy_request_buffering on;', 'proxy_buffer_size 8k;', 'proxy_buffers 8 8k;', 'proxy_busy_buffers_size 16k;', 'proxy_max_temp_file_size 64m;']) assert.match(bounded.artifacts[0].content, new RegExp(expected));
  const streaming = compose([proxy, buffering({profile: 'streaming', bufferSizeKb: undefined, bufferCount: undefined, busyBuffersSizeKb: undefined, maxTempFileSizeMb: undefined})]);
  assert.equal(streaming.ok, true, JSON.stringify(streaming.diagnostics));
  assert.match(streaming.artifacts[0].content, /proxy_buffering off;/u);
  assert.match(streaming.artifacts[0].content, /proxy_request_buffering off;/u);
  assert.ok(streaming.prerequisites.some(item => item.code === 'composition.proxy-buffering.streaming'));

  for (const mutation of [{busyBuffersSizeKb: 8}, {busyBuffersSizeKb: 64}, {bufferCount: 3}, {maxTempFileSizeMb: 1025}]) {
    const invalid = compose([proxy, buffering(mutation)]);
    assert.equal(invalid.ok, false, JSON.stringify(mutation));
  }
  assert.equal(compose([staticSite, buffering()]).ok, false);
});

test('new policies compose across multi-site and site-fragment profiles', () => {
  const result = composeNginxSites({profile: 'site-fragment', target, sites: [
    {id: 'api', capabilities: [proxy, security(), timeouts(), compression(), buffering()]},
    {id: 'static', capabilities: [staticSite, security({preset: 'strict'}), timeouts({proxy: undefined}), compression({types: ['text/css']})]},
  ]});
  assert.equal(result.ok, true, JSON.stringify(result.diagnostics));
  assert.match(result.artifacts[0].content, /server_name app\.example\.com;/u);
  assert.match(result.artifacts[0].content, /server_name static\.example\.com;/u);
  assert.equal((result.artifacts[0].content.match(/gzip on;/g) ?? []).length, 2);
  assert.deepEqual(result.artifacts.map(item => item.filename), ['site.conf', 'http-shared.conf']);
});

test('syntax registry enforces contexts and typed grammars for the new directives', () => {
  const source = {kind: 'capability', id: 'security-headers', version: '1.0.0'};
  const good = {profile: 'site-fragment', source, children: [block('server', [], [
    directive('add_header', [arg.headerName('X-Frame-Options'), arg.quoted('DENY'), arg.keyword('always')], source),
    directive('client_max_body_size', [arg.size('10m')], source),
    directive('gzip_types', [arg.mediaType('application/json')], source),
    directive('proxy_buffers', [arg.integer(8), arg.size('8k')], source),
  ], source)]};
  assert.equal(serializeNginxDocument(good).ok, true);
  const badContext = {profile: 'full-config', source, children: [directive('add_header', [arg.headerName('X-Test'), arg.quoted('yes')], source), block('events', [], [], source), block('http', [], [], source)]};
  assert.equal(serializeNginxDocument(badContext).ok, false);
  const badSize = {profile: 'site-fragment', source, children: [block('server', [], [directive('proxy_buffer_size', [arg.size('8k; return 200')], source)], source)]};
  assert.equal(serializeNginxDocument(badSize).ok, false);
});
